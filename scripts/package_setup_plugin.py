#!/usr/bin/env python3
"""Build only the reviewed Modulate Setup files into a deterministic download."""
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "plugins" / "modulate-setup"
DOWNLOADS = ROOT / "webapp" / "connect-app-code" / "public" / "downloads"
CONTENT = ROOT / "webapp" / "connect-app-code" / "src" / "modulate" / "setup-content.js"


def load_installer():
    spec = importlib.util.spec_from_file_location("modulate_plugin_install", SOURCE / "install.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def artifacts():
    version, files = load_installer().package_files(SOURCE)
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for relative, content in sorted(files.items()):
            info = zipfile.ZipInfo("modulate-setup/" + relative, date_time=(2026, 10, 29, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, content)
    zipped = output.getvalue()
    digest = hashlib.sha256(zipped).hexdigest()
    prompt = files["setup-prompt.txt"].decode().strip()
    javascript = (
        "// Generated by scripts/package_setup_plugin.py. Edit the plugin prompt source.\n"
        f"export const SETUP_PROMPT = {json.dumps(prompt, ensure_ascii=False)};\n"
        'export const SETUP_PLUGIN_URL = "/downloads/modulate-setup.zip";\n'
        f"export const SETUP_PLUGIN_VERSION = {json.dumps(version)};\n"
        f"export const SETUP_PLUGIN_SHA256 = {json.dumps(digest)};\n"
    ).encode()
    return {
        DOWNLOADS / "modulate-setup.zip": zipped,
        DOWNLOADS / "modulate-setup.sha256": f"{digest}  modulate-setup.zip\n".encode(),
        DOWNLOADS / "modulate-setup-prompt.txt": (prompt + "\n").encode(),
        CONTENT: javascript,
    }


def main():
    for path, content in artifacts().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    print("Built Modulate Setup plugin, checksum, prompt, and web content.")


if __name__ == "__main__":
    main()
